"""CONCORD semi-supervised training engine for NAViECO Layer0."""

from contextvars import ContextVar
from .progress import log_progress
_NAVIECO_TRAINING = ContextVar("navieco_training_progress", default=None)

from pathlib import Path
import concord as ccd
import torch


class _TrackedConcord(ccd.Concord):
    """Record real epoch losses without modifying CONCORD optimization."""

    def __init__(self, *args, **kwargs):
        self.navieco_history = []
        super().__init__(*args, **kwargs)

    def init_trainer(self):
        # CONCORD constructs its Trainer inside train(), so instrument it
        # immediately after construction and before training begins.
        super().init_trainer()

        train_original = self.trainer.train_epoch
        val_original = self.trainer.validate_epoch

        def train_record(epoch, dataloader):
            loss = train_original(epoch, dataloader)
            self.navieco_history.append({
                "epoch": int(epoch) + 1,
                "train_loss": float(loss),
                "val_loss": float("nan")
            })
            return loss

        def val_record(epoch, dataloader):
            loss = val_original(epoch, dataloader)
            if not self.navieco_history:
                raise RuntimeError("Validation occurred before training.")
            self.navieco_history[-1]["val_loss"] = float(loss)
            context = _NAVIECO_TRAINING.get()
            if context is not None:
                stage, requested = context
                row = self.navieco_history[-1]
                log_progress(
                    f"{stage} | epoch {row['epoch']}/{requested} "
                    f"| train_loss={row['train_loss']:.5f} "
                    f"| val_loss={row['val_loss']:.5f}"
                )
            return loss

        self.trainer.train_epoch = train_record
        self.trainer.validate_epoch = val_record


def _run_concord_impl(joint, save_dir, device="cpu", n_epochs=15, seed=42, verbose=True, latent_dim=300, batch_size=128):
    """Train CONCORD on labeled Reference cells and unlabeled Query cells.

    The classification loss uses curated Reference labels only, while contrastive
    representation learning includes both Reference and Query cells. The trained
    model and its configuration are saved for reproducibility.
    """
    required = {"navieco_label", "navieco_domain", "navieco_origin"}
    if not required.issubset(joint.obs.columns):
        raise ValueError(f"Joint input is missing columns: {required - set(joint.obs.columns)}")
    if "navieco_joint" not in joint.uns:
        raise ValueError("Input must be generated by build_joint().")
    if isinstance(latent_dim, bool) or not isinstance(latent_dim, int) or not 8 <= latent_dim <= 512:
        raise ValueError("latent_dim must be an integer between 8 and 512.")
    if isinstance(batch_size, bool) or not isinstance(batch_size, int) or batch_size < 2:
        raise ValueError("batch_size must be an integer >= 2.")
    if isinstance(seed, bool) or not isinstance(seed, int) or seed < 0:
        raise ValueError("seed must be a non-negative integer.")
    if not isinstance(n_epochs, int) or n_epochs < 1:
        raise ValueError("n_epochs must be a positive integer.")

    # Verify that only Reference cells have supervised labels. This prevents
    # accidentally training on pseudo-labels assigned to the external Query.
    is_ref = joint.obs["navieco_origin"].eq("reference")
    is_query = joint.obs["navieco_origin"].eq("query")
    if not is_ref.any() or not is_query.any():
        raise ValueError("Both Reference and Query cells are required.")
    if joint.obs.loc[is_ref, "navieco_label"].eq("unlabeled").any():
        raise ValueError("Reference contains unlabeled cells.")
    if not joint.obs.loc[is_query, "navieco_label"].eq("unlabeled").all():
        raise ValueError("Query cells must all have the 'unlabeled' class.")
    if joint.obs.loc[is_ref, "navieco_label"].nunique() < 2:
        raise ValueError("At least two Reference classes are required.")

    # The current development environment uses CPU-only PyTorch. A CUDA build
    # must be installed separately before GPU training is requested.
    if str(device).startswith("cuda") and not torch.cuda.is_available():
        raise RuntimeError("CUDA was requested, but the installed PyTorch cannot access a GPU.")
    save_dir = Path(save_dir)
    save_dir.mkdir(parents=True, exist_ok=True)

    # Preserve the HVG union and curated labels established by earlier modules.
    # Sparse loading avoids unnecessary dense preloading of large joint matrices.
    model = _TrackedConcord(
        adata=joint, save_dir=str(save_dir), input_feature=joint.var_names.tolist(),
        class_key="navieco_label", domain_key="navieco_domain",
        unlabeled_class="unlabeled", use_classifier=True,
        latent_dim=latent_dim, encoder_dims=[1000], batch_size=batch_size,
        n_epochs=n_epochs, train_frac=0.9, seed=seed, device=device,
        clr_beta=1.0, p_intra_knn=0.0, preload_dense=False,
        use_faiss=False, verbose=verbose
    )

    # CONCORD stores the latent embedding and classification predictions in
    # the working AnnData and writes the fitted model to the output directory.
    model.fit_transform(output_key="Concord", return_class=True, return_class_prob=True, save_model=True)
    return joint, model


__all__ = ["run_concord"]


def run_concord(joint, save_dir, device="cpu", n_epochs=15, seed=42,
                verbose=True, latent_dim=300, stage_name="CONCORD", batch_size=128):
    """Run the existing CONCORD algorithm with optional real-time progress."""
    token = _NAVIECO_TRAINING.set((stage_name, n_epochs) if verbose else None)
    log_progress(
        f"{stage_name} | start: cells={joint.n_obs:,}, genes={joint.n_vars:,}, "
        f"epochs={n_epochs}, latent={latent_dim}, device={device}", verbose
    )
    try:
        joint, model = _run_concord_impl(
            joint, save_dir, device=device, n_epochs=n_epochs,
            seed=seed, verbose=verbose, latent_dim=latent_dim, batch_size=batch_size
        )
        log_progress(
            f"{stage_name} | completed: "
            f"epochs_recorded={len(getattr(model, 'navieco_history', []))}", verbose
        )
        return joint, model
    except Exception as exc:
        log_progress(f"{stage_name} | ERROR: {type(exc).__name__}: {exc}", verbose)
        raise
    finally:
        _NAVIECO_TRAINING.reset(token)


